def _freeze() -> tuple[dict, ...]:
    frozen: list[dict] = []
    for index, (source, slack_context, text, mentions) in enumerate(_ROWS, 1):
        signal_id = str(uuid5(NAMESPACE, f"v2-signal-{index:03d}"))
        gold = []
        for mention_index, (surface, entity_type) in enumerate(mentions, 1):
            if text.count(surface) != 1:
                raise AssertionError((index, surface, text.count(surface)))
            start = text.index(surface)
            gold.append({
                "mention_id": f"v2-m-{index:03d}-{mention_index}",
                "start": start,
                "end": start + len(surface),
                "surface": surface,
                "entity_type": entity_type,
                "canonical_referent": None,
            })
        frozen.append({
            "signal_id": signal_id,
            "batch_id": f"v2-batch-{((index - 1) // 10) + 1}",
            "source_type": source,
            "slack_context": slack_context,
            "text": text,
            "gold": gold,
        })
    return tuple(frozen)


